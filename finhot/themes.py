@lru_cache(maxsize=None)
def _pattern(theme: str) -> re.Pattern:
    parts = []
    for kw in THEMES[theme].split("|"):
        kw = re.escape(kw)
        if re.fullmatch(r"[A-Za-z0-9\\-]+", kw):
            kw = rf"(?<![A-Za-z]){kw}(?![A-Za-z])"
        parts.append(kw)
    return re.compile("|".join(parts))


def themes_in(text: str) -> list[str]:
    """文本命中的题材（按词典顺序）。"""
    return [t for t in THEMES if _pattern(t).search(text)]


def board_themes(board_name: str) -> list[str]:
    """板块名映射到题材，如"电池化学品"→锂电储能，"视频媒体"→传媒游戏。"""
    name = re.sub(r"概念|板块|Ⅱ|Ⅲ|行业", "", board_name)
    return [t for t in THEMES if t == name or _pattern(t).search(name)]


