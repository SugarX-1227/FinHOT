def looks_like_company(name: str) -> bool:
    """过滤掉"关联个股"字段里混入的泛化关键词（历史数据中新浪的 投资/欧元/以色列 等）。"""
    if not name or len(name) < 2 or len(name) > 12 or name in _GENERIC:
        return False
    if name.isascii() and name.islower():  # 新浪给的英文小写代号，如 spacex
        return False
    return not _NOT_COMPANY.fullmatch(name)
