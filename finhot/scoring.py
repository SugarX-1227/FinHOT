# 例行操作/例行数据：信源都会转载（多源加分会把它们推得很高），直接封顶
_ROUTINE_RE = re.compile(r"隔夜逆回购|天期逆回购|操作量为零|公开市场操作|RRP|国库券|投标倍数|中标利率|中间价报|中间价较上日|"
                         r"中间价调[升降]|储蓄国债.{0,6}开售|凭证式国债")
ROUTINE_CAP = 5.5


def classify(it: NewsItem) -> str:
    if it.lang == "en":
        return "海外"
    for text in (it.title, it.content[:150]):
        for cat, pat in _CATEGORY_RULES:
            if cat == "公司" and text is not it.title:
                continue  # "XX：" 公司句式只对标题有效
            if pat.search(text):
                return cat
    return "行业"


def rule_score(it: NewsItem) -> float:
    text = f"{it.title} {it.content[:200]}"
    s = 3.0
    votes = it.imp_votes or (it.imp_weight if it.important else 0.0)
    s += min(2.5, 1.5 * votes)                   # 信源"重要"标记（按信源可信度加权）
    if it.tier == "official":
        s += 1.5
    n_src = 1 + len(it.dup_sources)
    s += min(2.5, 0.7 * (n_src - 1))             # 多家同时报道 → 更重要
    s += (it.weight - 1.0)
    s += min(3.0, sum(w for w, p in _BOOST_RULES if p.search(text)))
    s -= min(4.0, sum(w for w, p in _NOISE_RULES if p.search(it.title)))
    if len(it.content) < 25 and not it.important:
        s -= 1.0
    if it.lang == "en":
        s -= 0.5  # 英文源作补充，默认略降权
    if _ROUTINE_RE.search(it.title) and not re.search(r"\d+万亿|买断式|降准|降息|MLF|PSL", it.title):
        s = min(s, ROUTINE_CAP)
    return round(max(0.0, min(10.0, s)), 2)


def score_all(items: list[NewsItem]) -> list[NewsItem]:
    for it in items:
        it.category = classify(it)
        it.score = rule_score(it)
    items.sort(key=lambda x: (x.score, x.published), reverse=True)
    return items
